static inline bool zf_sensorif_front_config_address(hwaddr addr)
{
    for (unsigned i = 0; i < sizeof(zf_sensorif_front_offsets) /
                                  sizeof(zf_sensorif_front_offsets[0]); i++) {
        if (addr == UINT64_C(0x15080000) + zf_sensorif_front_offsets[i]) {
            return true;
        }
    }
    return false;
}
static inline bool zf_sensorif_primary_address(hwaddr addr)
{
    switch (addr) {
    case 0x15080010: case 0x15080014: case 0x15080018: case 0x1508001c:
    case 0x15080020: case 0x15080024: case 0x15080028: case 0x1508002c:
    case 0x15080030: case 0x15080034: case 0x15080038: case 0x1508003c:
    case 0x15080040: case 0x15080044: case 0x15080048: case 0x15080050:
    case 0x15080054: case 0x15080068: case 0x1508006c:
        return true;
    default:
        return zf_sensorif_front_config_address(addr);
    }
}
