/*
 * Nikon Z 6III -- the ISP_APB device family at 0x150c0000, and its siblings.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 *
 * How this block was found
 * ------------------------
 * The machine stopped on a 4-byte read of 0x150c0018 from pc=0x040c1fd58,
 * then on a write of the same address from pc=0x040c1fd68. Those two PCs are
 * `LDR W9,[X8,#0x18]` and `STR W9,[X8,#0x18]` inside sub_40C1FD50, which is
 * the set-or-clear-bits accessor:
 *
 *     LDR X8, [X0,#8]      ; the device base, out of the handle
 *     TST W2, #1
 *     LDR W9, [X8,#0x18]
 *     ORR W10, W9, W1
 *     BIC W9, W9, W1
 *     CSEL W9, W10, W9, NE
 *     STR W9, [X8,#0x18]
 *
 * A read-modify-write that never tests what it read back, so storage is the
 * firmware's own stated expectation for this register, not an invention.
 *
 * One driver, many instances
 * --------------------------
 * The base is not an immediate. It comes from the device descriptor table in
 * `.data`, at flat 0x451fe5a8 onward in the image (runtime 0xa0280d5a8,
 * using the measured .data delta 0x9bd60f000). Each entry there is a device
 * id followed by its MMIO base, and the whole family shares one group of
 * four driver entry points at flat 0x451fe588-0x451fe5a0 (0x40c1b704,
 * 0x40c1b848, 0x40c1b89c, 0x40c1b8a0). The table reads:
 *
 *   id    base
 *   0x192  0x150ce000
 *   0x193  0x150ce400
 *   0x194  0x150d4000
 *   0x195  0x150d5000
 *   0x196  0x150ce800
 *   0x197  0x150d5100
 *   0x198  0x150d5200
 *   0x199  0x150c8000
 *   0x19a  0x150cb000
 *   0x19b  0x150d4c00
 *   0x19c  0x150d4e00
 *   0x19d  0x150c0400
 *   0x1a0  0x150c0000
 *   0x19e  0x150d9a00
 *   0x19f  0x150d9800
 *   0x1a1  0x150d6000
 *   0x1a2  0x150d8000
 *   0x1a3  0x150d0000
 *   0x1a4  0x150d2000
 *
 * So the register set below is the family's, not one instance's, and the
 * other instances will appear as stops at their own bases when the firmware
 * first reaches them. Each is then one line here, not a new investigation.
 *
 * The window is 0x400 and not larger, because the table itself says so:
 * 0x150c0000 and 0x150c0400 are different devices, as are 0x150d5000,
 * 0x150d5100 and 0x150d5200, which are 0x100 apart. An offset scan that
 * ignored that produced offsets up to 0x7fc and was mixing device types
 * together; the bound is the firmware's, not a convenience.
 *
 * The register set
 * ----------------
 * 209 offsets, highest 0x3a8, every one of them a constant offset
 * that some instruction in 0x40c1b000-0x40c28000 applies to a [X0,#8]-derived
 * base -- 258 functions in all, extracted by z63-tools/handle_offsets.py
 * with --limit 0x400. 0x000 through 0x1f4 is dense: every 4-byte word in
 * that span is named. The gaps above it are real gaps and still stop.
 *
 * 10 of these offsets are only ever read, never written. For those, storage
 * is a DECLARED CHOICE -- this model returns the reset value and nothing
 * here knows what the hardware would report. A firmware poll on a bit real
 * silicon raises would hang rather than stop; z63-tools/where_blocked.py is
 * the instrument for that.
 */

