/*
 * Nikon Z 6III -- devices 0x1cf and 0x1d0, at 0x15100000 and 0x15140000.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 *
 * The firmware's device table names both, next to each other, with a DRAM
 * buffer for each. At flat 0x451f96a8 onward (runtime 0xa028086a8, flat +
 * the measured .data delta 0x9bd60f000) it reads:
 *
 *     0x1cf  0x15100000          0x1cf  0xa1baa1b00
 *     0x1d0  0x15140000          0x1d0  0xa1baa8b00
 *
 * so the pair, the stride and the instance count are all read out of the
 * image rather than inferred, and the DRAM addresses say each instance has a
 * buffer rather than only registers.
 *
 * sub_40C0D830 drives both at once through their descriptors, which is how
 * the machine found them -- two stops on the same instruction pair:
 *
 *     LDR  X8, [X19,#8]           ; instance 0x1cf's base
 *     STR  W21, [X8,#0xc]         ; 0x40c0d898
 *     LDR  X8, [X20,#8]           ; instance 0x1d0's base, X20 = 0xa028086c0
 *     STR  W21, [X8,#0xc]         ; 0x40c0d8a0
 *     ...
 *     STR  W9, [X8,#0x14]         ; W9 = 0x3807f
 *     STR  W21, [X8]
 *
 * The group's four driver entry points are above the pair in the table, at
 * flat 0x451f9688: 0x40c0d6cc, 0x40c0d6f8, 0x40c0d714, 0x40c0d718.
 *
 * The register set
 * ----------------
 * 588 offsets, highest 0x641c, from 183 functions in
 * 0x40c0c000-0x40c13000, by z63-tools/handle_offsets.py --field 8: a forward
 * dataflow over the basic-block graph recording every constant offset
 * applied to a base loaded from a descriptor's +8 field.
 *
 * The window is 0x40000 per instance because that is the table's spacing, and
 * the highest offset in the set is well inside it.
 *
 * What is a declared choice
 * -------------------------
 * Storage, and applying one register set to both instances. The second rests
 * on the two being one driver's devices in one table group, which the table
 * states; each instance's own accesses have not been separated.
 *
 * 10 offsets are only ever read, never written. For those the reset value
 * is returned and nothing here knows what hardware would report. An offset
 * not in the set still stops the machine with its PC.
 */

