/*
 * Nikon Z 6III -- sensor interface, 0x15080000, inside ISP_APB.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 *
 * Which image this was read from
 * ------------------------------
 * `eg2010_0200i1.bi`, md5 b024ec7148e24ec0493e27d4d0f20b0e -- the file this
 * board loads at 0x40160000. The matching IDA database is `z63_eg.elf`
 * (md5 0fedcc0523da1dac8127a8010ccf978b), and every code address below was
 * taken from it and cross-checked against the raw bytes of the .bi.
 *
 * This matters more than it looks. There is a second EXPEED 7 database for a
 * different image, `vr2070.elf`, whose register layout is nearly identical
 * and in which most functions sit at the same addresses -- but not all of
 * them, and its data layout differs: it puts the record table described
 * below at 0x4164bf18, where the shipped image has code. Reading the shipped
 * image's PCs through that database produces plausible, wrong answers.
 *
 * What the block is
 * -----------------
 * The base never appears as an immediate. It arrives in a descriptor, and
 * every accessor starts `LDR Xn, [X0,#8]` and applies a constant offset.
 * Two independent facts pin it to 0x15080000:
 *
 *   - sub_40C2C9A4 reads [base+0x44] at 0x40c2c9c4, ORs in one 32-bit mask
 *     per entry of the fifteen-entry table at 0x4184b764, and writes it back
 *     at 0x40c2c9e8. The first unmodelled access this board reported here
 *     was a 4-byte read of 0x15080044, from pc=0x040c2c9c4 -- the same
 *     instruction.
 *   - sub_40C2CB5C walks the record table at 0x4184b7e0: fifteen 0x30-byte
 *     records, the match key at +0x00 and a register pointer at +0x08, for
 *     fourteen iterations (CMP W11,#0xE at 0x40c2cb8c). Record 14's pointer
 *     is 0x150833c8, and the machine stopped on a write of exactly that
 *     address from pc=0x040c2cbb0 (`STR W10,[X8]`) and then of +4 from
 *     pc=0x040c2cc10. Record 14 is also the one whose +0x28 field is zero,
 *     which is why sub_40C2CB5C has the `ADD X9,X10,#0x3f0` fallback -- a
 *     handle-relative offset, confirming the same base from the other side.
 *
 * The region table at .data 0xa02bd2380 places 0x15080000 in ISP_APB, and
 * the Z 8 board in ../n-research/z8-qemu calls it Z8_SENSOR_IF_BASE.
 *
 * Where the offsets come from
 * ---------------------------
 * Three sources, none of them a VM stop and none of them a guess:
 *
 *   1. 243 offsets from z63-tools/handle_offsets.py over
 *      0x40c2a000-0x40c2e000: every constant offset any of 83 functions
 *      there applies to a [X0,#8]-derived base, by a forward dataflow over
 *      the basic-block graph.
 *   2. 261 further offsets named only by the record table, which no
 *      offset scan can see: sub_40C2CB5C loads an absolute address out of it
 *      and stores through ptr+0x00..ptr+0x28, so each record pointer
 *      contributes that span. This is the class that produced +0x33c8.
 *   3. 4 further offsets from z63-tools/window_pointers.py: any
 *      aligned 64-bit word anywhere in the image whose value lands in this
 *      window -- +0xb04, +0x1000, +0x2000, +0x4000. Holding an
 *      address is weaker evidence than storing through it, so these are the
 *      first place to look if this block ever behaves oddly.
 *
 * 508 offsets in all, highest 0x4000.
 *
 * An earlier pass walked these functions in address order instead of in
 * execution order. That is not a weaker version of this analysis, it is a
 * wrong one: it applies one branch's offset to a register another branch has
 * already overwritten. It reported 33 offsets this block does not have --
 * among them a tidy-looking set of fifteen register pairs at +0x450, +0x968,
 * +0xe10 and so on up to +0x47b0, which invited the reading that they were
 * per-lane status, fifteen of them for the fifteen records. They are an
 * artefact of the walk. It also missed 79 offsets that are real, including
 * the four that sub_40C2BD0C selects between with a CSEL chain. The lesson
 * is in the header of handle_offsets.py.
 *
 * What is a declared choice
 * -------------------------
 * Storage. Most of these offsets are written by the firmware, several
 * read-modify-written, and for those, reading back what was written is the
 * firmware's own stated expectation rather than an invention.
 *
 * 65 of the harvested offsets are only ever read, never written, which is
 * the shape of a status register. For those, storage is a DECLARED CHOICE:
 * this model returns the reset value and nothing here knows what the
 * hardware would report. If the firmware polls one for a bit real silicon
 * raises, it will spin -- a hang, not a stop, and z63-tools/where_blocked.py
 * is the instrument for that case. They are listed in
 * z63_sensorif_status_offsets[] so the next person need not re-derive them.
 *
 * An offset not in the set still stops the machine with its PC. That is how
 * +0x44, +0x48, +0x000, +0x33c8, +0x33cc and the +0x60-strided group at
 * +0x10c were each found, and it is the only way the next one will be;
 * widening this to the whole window would trade every remaining lead for a
 * silent zero.
 */

