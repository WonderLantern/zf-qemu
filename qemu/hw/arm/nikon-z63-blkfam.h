/*
 * Nikon Z 6III -- the five-instance block family at 0x15340000, 0x40000 apart.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 *
 * This replaces three separate windows -- 0x15340000, 0x15380000 and
 * 0x15440000 -- that were modelled one VM stop at a time before the pattern
 * was visible. It became visible when a fourth stop landed on 0x153c0044:
 * 0x15340000, 0x15380000, 0x153c0000 and 0x15440000 are 0x40000, 0x40000 and
 * 0x80000 apart, so it is one family on a 0x40000 stride with 0x15400000 not
 * yet reached.
 *
 * Where the bounds come from
 * --------------------------
 * The low end is the firmware's own device table (docs/register-windows.md
 * has the table): at flat 0x451fe7f0 it reads {0x185, 0x15340000,
 * 0xa02dc4900} and at 0x451fe810 {0x186, 0x15380000, 0xa02dc5100}.
 * sub_40C27E78 brings both up by id, taking each base from its slot and
 * clearing +0x14 on both at 0x40c27ed0/0x40c27ed4 -- the stop that first
 * exposed the family.
 *
 * The high end is not a guess either: 0x15340000 + 5 * 0x40000 is exactly
 * 0x15480000, the display controller base, independently established at
 * `.data` 0xa02808438 under id 0x1c7 (see nikon-z63-display.h). Five
 * instances is where this family has to stop.
 *
 * The three ways the firmware names it, all observed:
 *
 *   0x15340000, 0x15380000   descriptor slots, sub_40C27E78
 *   0x153c0000               read-modify-write of +0x44, 0x40c24974/0x40c2497c
 *   0x15440000               a materialised constant in sub_40C2550C:
 *                            MOV X8,#0x308 ; MOVK X8,#0x1544,LSL#16 ; STR WZR,[X8]
 *
 * which is why the register set is harvested per base and unioned rather
 * than taken from whichever one happened to stop first.
 *
 * The register set
 * ----------------
 * 680 offsets, highest 0xc024, the union of two harvests over
 * 0x40c20000-0x40c30000 by z63-tools/handle_offsets.py: --array-base for the
 * descriptor-reached instances and --const-window for the constant-reached
 * one. The array-base harvest found 541 offsets and every one of them is
 * also in the const-window harvest. That complete containment is the main
 * reason for believing the family is one family.
 *
 * Both harvests are a forward dataflow over the basic-block graph. The
 * --const-window mode is the loosest of the four base shapes: a constant the
 * firmware computes but never dereferences is counted, so the set may be
 * wider than the hardware's register file. That costs nothing, since nothing
 * else maps these windows, but it can absorb an access worth seeing, and it
 * makes this the first family to re-derive if something here looks wrong.
 *
 * What is a declared choice
 * -------------------------
 * Storage, and the stride. 91 offsets are only ever read, never written;
 * for those this model returns the reset value and knows nothing about what
 * hardware would report. Applying one register set to all five instances is
 * also a DECLARED CHOICE -- the driver is shared and the two harvests agree,
 * but nothing has been observed at 0x15400000 at all.
 *
 * An offset not in the set still stops the machine with its PC.
 */

